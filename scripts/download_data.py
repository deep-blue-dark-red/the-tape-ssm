GROUPS = {
    "ltsf": ["ett", "weather", "exchange", "electricity", "traffic"],
    "cmapss": ["cmapss"],
    "stformer": ["metr-la", "pems-bay"],
    "irregular": ["tpatchgnn", "physiome", "easytpp", "timeimm", "pyrregular"],
    "tpp": ["easytpp"],
    "opensky": ["opensky-aircraft"],
}
GROUPS["all"] = GROUPS["ltsf"] + GROUPS["cmapss"] + GROUPS["stformer"] + GROUPS["irregular"]

OPENSKY_NOTE = """\
  opensky-snapshot: NOT DOWNLOADABLE.  OpenSky's one-day Trino snapshot (2026-03-01) was withdrawn
    from s3.opensky-network.org/data-samples/trino-tables/ (placeholder since 2026-11-04).  If you
    hold a copy, put it under data/opensky/trino_snapshot_2026-03-01/ and run --verify-only opensky-snapshot;
    data/checksums/opensky.sha256 pins all 26 parquet files."""


def resolve(names: list[str]) -> list[str]:
    out: list[str] = []
    for n in names or ["all"]:
        if n == "opensky-snapshot":
            out.append(n)
        elif n in GROUPS:
            out.extend(GROUPS[n])
        elif n in DATASETS:
            out.append(n)
        else:
            raise SystemExit(f"unknown dataset or group {n!r}; see --list")
    return list(dict.fromkeys(out))


def main() -> int:
    global ROOT, EXPECTED
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("names", nargs="*", help="datasets or groups (default: all)")
    ap.add_argument("--list", action="store_true", help="list datasets and groups")
    ap.add_argument("--verify-only", action="store_true", help="hash what is on disk; download nothing")
    ap.add_argument("--force", action="store_true", help="re-download even when the files verify")
    ap.add_argument("--keep-archives", action="store_true", help="keep Physiome-ODE's final.zip after unpacking")
    ap.add_argument("--root", type=Path, default=None, help="data tree root (default: the repo)")
    args = ap.parse_args()

    if args.list:
        for n, (_, _, desc, _) in DATASETS.items():
            log(f"  {n:17s} {desc}")
        log("  opensky-snapshot  OpenSky 2026-03-01 Trino snapshot (withdrawn upstream; verify only)")
        for g, members in GROUPS.items():
            log(f"  [{g}] {' '.join(members)}")
        return 0

    ROOT = (args.root or REPO).resolve()
    EXPECTED = load_manifests()
    if not EXPECTED:
        log(f"warning: no manifests in {MANIFESTS}; files will be fetched but not verified")

    ok = True
    for name in resolve(args.names):
        if name == "opensky-snapshot":
            log(OPENSKY_NOTE) if not args.verify_only else None
            ok &= verify(["data/opensky/trino_snapshot_2026-03-01/", "data/opensky/trino_snapshot.keys"], name)
            continue
        fn, prefixes, desc, warn_only = DATASETS[name]
        log(f"== {name}: {desc}")
        if not args.verify_only:
            if not args.force and complete(prefixes):
                log("  already present and verified; skipping")
                continue
            with tempfile.TemporaryDirectory(prefix=f"tw-{name}-") as tmp:
                try:
                    if name == "physiome":
                        fn(Path(tmp), keep=args.keep_archives)
                    else:
                        fn(Path(tmp))
                except Exception as e:  # noqa: BLE001 — keep going with the other datasets
                    log(f"  ERROR: {e}")
                    ok = False
                    continue
        ok &= verify(prefixes, name, warn_only=warn_only)
    log("done" if ok else "done, with failures (see above)")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
