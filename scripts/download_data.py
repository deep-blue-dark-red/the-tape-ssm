# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def log(msg: str) -> None:
    print(msg, flush=True)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(1 << 22):
            h.update(chunk)
    return h.hexdigest()


def fetch(url: str, dest: Path, retries: int = 3) -> Path:
    """Stream ``url`` to ``dest`` through a .part file; retry on network errors."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_name(dest.name + ".part")
    for attempt in range(1, retries + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
            with urllib.request.urlopen(req, timeout=60) as r, open(part, "wb") as f:
                total = int(r.headers.get("Content-Length") or 0)
                done, next_report, t0 = 0, 0.1, time.time()
                while chunk := r.read(1 << 20):
                    f.write(chunk)
                    done += len(chunk)
                    if total and done / total >= next_report:
                        log(f"    {dest.name}: {done / 1e6:7.1f} / {total / 1e6:.1f} MB "
                            f"({done / max(time.time() - t0, 1e-3) / 1e6:.1f} MB/s)")
                        next_report += 0.25
            part.replace(dest)
            return dest
        except Exception as e:  # noqa: BLE001 — report and retry any transfer failure
            part.unlink(missing_ok=True)
            if attempt == retries:
                raise RuntimeError(f"download failed after {retries} tries: {url}: {e}") from e
            log(f"    retry {attempt}/{retries - 1} after error: {e}")
            time.sleep(3 * attempt)
    raise AssertionError("unreachable")


def safe_extract(zip_path: Path, dest: Path, members: list[str] | None = None) -> None:
    """Extract a zip, refusing absolute paths and '..' components (zip-slip)."""
    dest = dest.resolve()
    with zipfile.ZipFile(zip_path) as z:
        names = members or z.namelist()
        for name in names:
            target = (dest / name).resolve()
            if dest not in target.parents and target != dest:
                raise RuntimeError(f"unsafe path in {zip_path.name}: {name}")
        for name in names:
            if "__MACOSX" in name or name.endswith(".DS_Store"):
                continue
            z.extract(name, dest)


def git(*args: str, cwd: Path | None = None) -> None:
    subprocess.run(["git", *args], cwd=cwd, check=True)


def write_bytes_atomic(dest: Path, data: bytes) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_name(dest.name + ".part")
    tmp.write_bytes(data)
    tmp.replace(dest)


def strip_cr(src: Path, dest: Path) -> None:
    write_bytes_atomic(dest, src.read_bytes().replace(b"\r", b""))


# ---------------------------------------------------------------------------
# manifests
# ---------------------------------------------------------------------------

def load_manifests() -> dict[str, str]:
    """repo-relative path -> expected SHA-256, over every data/checksums/*.sha256."""
    out: dict[str, str] = {}
    for m in sorted(MANIFESTS.glob("*.sha256")):
        for line in m.read_text().splitlines():
            if line.strip():
                digest, rel = line.split("  ", 1)
                out[rel] = digest
    return out


EXPECTED: dict[str, str] = {}


def expected_files(prefixes: list[str]) -> dict[str, str]:
    return {rel: h for rel, h in EXPECTED.items() if any(rel.startswith(p) for p in prefixes)}


def verify(prefixes: list[str], label: str, warn_only: bool = False) -> bool:
    """Hash every manifest file under ``prefixes``; print a one-line verdict per dataset."""
    files = expected_files(prefixes)
    if not files:
        present = [p for p in prefixes if (ROOT / p).exists()]
        log(f"  {label}: no manifest entries; {'present' if present else 'absent'}, not verified")
        return True
    missing, differ = [], []
    for rel, digest in files.items():
        path = ROOT / rel
        if not path.exists():
            missing.append(rel)
        elif sha256(path) != digest:
            differ.append(rel)
    ok = not missing and not differ
    word = "OK" if ok else ("WARN" if warn_only else "FAIL")
    log(f"  {label}: {word} {len(files) - len(missing) - len(differ)}/{len(files)} match"
        + (f", {len(missing)} missing" if missing else "") + (f", {len(differ)} DIFFER" if differ else ""))
    for rel in differ:
        log(f"      DIFFERS: {rel}")
    for rel in missing[:5]:
        log(f"      missing: {rel}")
    if len(missing) > 5:
        log(f"      ... and {len(missing) - 5} more missing")
    return ok or warn_only


def complete(prefixes: list[str]) -> bool:
    """True when every manifest file under ``prefixes`` exists with the right hash."""
    files = expected_files(prefixes)
    return bool(files) and all((ROOT / r).exists() and sha256(ROOT / r) == h for r, h in files.items())


