def get_ett(tmp: Path) -> None:
    for name in ("ETTh1", "ETTh2", "ETTm1", "ETTm2"):
        fetch(f"{ETT_RAW}/{name}.csv", ROOT / "data/ltsf_raw" / f"{name}.csv")


def get_weather(tmp: Path) -> None:
    # The Autoformer / TSLib copy has CRLF line endings; the committed file is the same bytes with LF.
    strip_cr(fetch(f"{HF_TSLIB}/weather/weather.csv", tmp / "weather.csv"), ROOT / "data/ltsf_raw/weather.csv")


def get_exchange(tmp: Path) -> None:
    strip_cr(fetch(f"{HF_TSLIB}/exchange_rate/exchange_rate.csv", tmp / "exchange_rate.csv"),
             ROOT / "data/ltsf_raw/exchange_rate.csv")


def get_electricity(tmp: Path) -> None:
    fetch(f"{HF_TSLIB}/electricity/electricity.csv", ROOT / "data/ltsf_raw/electricity.csv")


def _mac_number(token: str) -> str:
    """A value as the Mac copy of traffic.csv spells it: Python's shortest round-trip form,
    except that 0.0001 is written ``1e-04``.  The rule is empirical: over all 15.1 M values of
    LSTNet's file this is the only spelling that differs from ``repr`` (0.0002 ... 0.0009 stay
    fixed-point), and with it the rebuild is byte-identical to the hashed file."""
    x = float(token)
    return "1e-04" if x == 0.0001 else repr(x)


def get_traffic(tmp: Path) -> None:
    # data/traffic.csv: the Autoformer / TSLib copy (header 0..860,OT; 136 MB).
    fetch(f"{HF_TSLIB}/traffic/traffic.csv", ROOT / "data/traffic.csv")
    # data/ltsf_raw/traffic.csv: the same values (LSTNet traffic.txt) with a sensor_0..861 header and
    # hourly dates from 2015-01-01.  Rebuilt byte for byte (see _mac_number).
    raw = gzip.decompress(fetch(LSTNET_TRAFFIC, tmp / "traffic.txt.gz").read_bytes()).decode()
    rows = raw.splitlines()
    n = len(rows[0].split(","))
    t0 = dt.datetime(2015, 1, 1)
    out = ["date," + ",".join(f"sensor_{i}" for i in range(n))]
    for i, row in enumerate(rows):
        stamp = (t0 + dt.timedelta(hours=i)).strftime("%Y-%m-%d %H:%M:%S")
        out.append(stamp + "," + ",".join(_mac_number(v) for v in row.split(",")))
    write_bytes_atomic(ROOT / "data/ltsf_raw/traffic.csv", ("\n".join(out) + "\n").encode())


def get_cmapss(tmp: Path) -> None:
    dest = ROOT / "data/cmapss"
    outer = fetch(CMAPSS_ZIP, tmp / "cmapss_outer.zip")
    safe_extract(outer, tmp / "outer")
    inner = next((tmp / "outer").rglob("CMAPSSData.zip"))      # the PHM mirror nests the NASA zip
    safe_extract(inner, tmp / "inner")
    dest.mkdir(parents=True, exist_ok=True)
    for f in (tmp / "inner").rglob("*"):
        if f.is_file() and (f.suffix == ".txt" or f.suffix == ".pdf"):
            shutil.copy2(f, dest / f.name)


def _stformer(name: str, tmp: Path) -> None:
    raw = ROOT / "data/traffic/raw" / name
    stem = "in_12_out_12_rescale_True"
    zname = "data.zip" if name == "METR-LA" else f"data_{stem}.zip"   # the name the manifest records
    z = fetch(f"{STFORMER_RAW}/{name}/data_{stem}.zip", raw / zname)
    safe_extract(z, tmp / name)
    pkl = next((tmp / name).rglob(f"data_{stem}.pkl"))
    shutil.move(str(pkl), raw / pkl.name)
    for f in (f"index_{stem}.pkl", f"scaler_{stem}.pkl", "adj_mx.pkl"):
        fetch(f"{STFORMER_RAW}/{name}/{f}", raw / f)


def get_metr_la(tmp: Path) -> None:
    _stformer("METR-LA", tmp)


def get_pems_bay(tmp: Path) -> None:
    _stformer("PEMS-BAY", tmp)


def get_tpatchgnn(tmp: Path) -> None:
    git("clone", "-q", "--depth", "1", TPATCHGNN_GIT, str(tmp / "tpatchgnn"))
    src, dest = tmp / "tpatchgnn" / "data", ROOT / "data/irregular/tpatchgnn"
    for sub in ("activity", "ushcn"):
        shutil.copytree(src / sub, dest / sub, dirs_exist_ok=True)
    (dest / "physionet").mkdir(parents=True, exist_ok=True)
    for z in (src / "physionet").glob("*.zip"):
        shutil.copy2(z, dest / "physionet" / z.name)
    proc = dest / "physionet" / "processed.zip"
    if proc.exists():
        safe_extract(proc, dest / "physionet")
        proc.unlink()


def get_physiome(tmp: Path, keep: bool = False) -> None:
    dest = ROOT / "data/irregular/physiome_ode"
    z = fetch(PHYSIOME_ZIP, dest / "final.zip")
    md5 = hashlib.md5()
    with open(z, "rb") as f:
        while chunk := f.read(1 << 22):
            md5.update(chunk)
    if md5.hexdigest() != PHYSIOME_MD5:
        raise RuntimeError(f"final.zip md5 {md5.hexdigest()} != Zenodo's {PHYSIOME_MD5}")
    safe_extract(z, dest)
    if not keep:
        z.unlink()


def get_easytpp(tmp: Path) -> None:
    for name in ("taxi", "stackoverflow", "retweet", "taobao"):
        for part in ("train", "dev", "test"):
            fetch(f"{EASYTPP_HF}/{name}/resolve/main/{part}.json",
                  ROOT / "data/irregular/easytpp" / name / f"{part}.json")


def get_easytpp_jitter(tmp: Path) -> None:
    script = REPO / "scripts" / "make_jittered_easytpp.py"
    if not script.exists():
        log("    scripts/make_jittered_easytpp.py is not in this checkout; skipping the derived copies")
        return
    if ROOT != REPO:
        log("    make_jittered_easytpp.py writes into the repo's data/ tree; run it without --root")
        return
    for name in ("stackoverflow", "retweet"):
        subprocess.run([sys.executable, str(script), name, "--seed", "20261105"], check=True, cwd=REPO)


def get_timeimm(tmp: Path) -> None:
    dest = ROOT / "data/irregular/timeimm"
    if not (dest / ".git").exists():
        if dest.exists() and any(dest.iterdir()):
            raise RuntimeError(f"{dest} exists and is not a git checkout; move it aside first")
        git("init", "-q", str(dest))
        git("remote", "add", "origin", TIMEIMM_GIT, cwd=dest)
    git("fetch", "-q", "--depth", "1", "origin", TIMEIMM_COMMIT, cwd=dest)
    git("checkout", "-q", TIMEIMM_COMMIT, cwd=dest)


def get_pyrregular(tmp: Path) -> None:
    for name in PYRREGULAR_FILES:
        path = ROOT / "data/irregular/pyrregular" / f"{name}.h5"
        rel = path.relative_to(ROOT).as_posix()
        if path.exists() and EXPECTED.get(rel) == sha256(path):
            continue
        fetch(f"{PYRREGULAR_HF}/{name}.h5", path)


def get_opensky_aircraft(tmp: Path) -> None:
    fetch(OPENSKY_AIRCRAFT, ROOT / "data/opensky/aircraftDatabase.csv")
    log("    note: aircraftDatabase.csv is a moving file upstream; a hash mismatch means a newer copy")


