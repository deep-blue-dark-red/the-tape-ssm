#!/usr/bin/env python3
"""Download every dataset TapeWorld reads and verify it against data/checksums/.

    python3 scripts/download_data.py                  # everything in the `all` group
    python3 scripts/download_data.py ltsf cmapss      # groups or single datasets
    python3 scripts/download_data.py --list           # what is available
    python3 scripts/download_data.py --verify-only    # hash what is on disk, fetch nothing
    python3 scripts/download_data.py --root /tmp/tw   # write under another tree

Standard library only (plus ``git`` for the two repositories that ship data as a clone).
Each dataset is skipped when its files are already present and match the manifests; a file
whose SHA-256 differs from ``data/checksums/<collection>.sha256`` is reported as DIFFERS and
the run exits non-zero.  The manifests record the exact bytes the published rows used
(README.md, "Datasets"); ``scripts/hash_datasets.py`` writes them.

Groups:
    ltsf      ett weather exchange electricity traffic
    cmapss    cmapss
    stformer  metr-la pems-bay
    irregular tpatchgnn physiome easytpp timeimm pyrregular
    tpp       easytpp
    opensky   opensky-aircraft  (the 2026-03-01 Trino snapshot was withdrawn upstream)
    all       ltsf + cmapss + stformer + irregular

Simulated datasets (OU, Hawkes, Lotka-Volterra, switching LDS) need no download: they are
generated by data/generators/.  The E14 jittered EasyTPP copies are derived; ``easytpp-jitter``
rebuilds them with scripts/make_jittered_easytpp.py when that script is present.
"""

